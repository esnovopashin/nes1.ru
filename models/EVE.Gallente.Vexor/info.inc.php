Только тогда можно приступать к нарезке.<br>
Повезло. Искажения минимальны и при коррекции текстуры не "поплывут", т.е., не будет искажения линий.<br>
Проведя несколько вечеров в коррекции формы и выведя Vexor в симметричный вид, наконец-то, разделяем его на части. Трубопроводы отделяем полностью, одной деталью.<br>
Становится понятно, каким образом будет сделан каркас. В какой последовательности будет собираться модель.
Упрощаем.<br>
Тут следует отметить, что при реальной длине Vexor`a = 218 м, я буду делать его длиной 218мм (1:1000). Значит, часть элементов станет на столько мала в размерах, что их можно "упростить" на этапе моделлинга: удалить или впаять в общие плоскости больших деталей.<br>
Параллельно исправляются мелкие косяки: взаимопроникновение плоскостей друг в друга, несклейка вертексов и подобные стандартные моменты.<br>
<i>Возникла мысль передать текстуру на коррекцию Slaider`у: оригинальная низкого разрешения, зернистая. Посмотрим, что скажет Мастер.</i>
<br>
Вот тут стало совсем интересно: как бы мы не меняли разрешение и плотность точек текстуры, Пепа все равно "растрит" итог: появляются лесенки на диагональных линиях, размываются контрастные области.<br>
Придется, все же, вручную работать с текстурой... мдя... для этого нужно больше времени, чем хотелось бы...<br>
Ок, ставим дедлайн сдачи готового экземпляра на 1е сентября и пилим дальше.<br>
Начнем с каркаса.<br>
Так как вся модель, ее конечный вид, очень сильно зависят от ее формы, очень важно, чтобы при сборке форму не повело. Значит, будем ваять каркас.<br>
