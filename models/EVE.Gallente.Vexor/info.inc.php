19.04.2020<br>
"... Давайте начнем с Vexor`a..."<br>
Началась разработка. Оказалось, что я зря сторонился кривых 2го порядка. А именно, пузато-шарообразных "оплавленных" кораблей Gallente<br>
&nbsp;<br>
Итак, начнем.<br>
Архивируем папку с восстанавливаемым Кестрелем (что-то не так у меня с этим кораблем. Все никак не доведу до качественнного релиза) и раскапываем архив насканенных моделей EVE.<br>
Когда надежда уже допила чай и начала напяливать сапожки, Vexor в хорошем количестве полигонов обнаруживается в весьма неожиданном месте: болтался среди астероидов среди кучи шахтеров.<br>
Хорошо.<br>
Как обычно, выдираем модель из сцены. Чистим текстуры и материалы, оставляя только нужное.<br>
Снимаем сглаживание. Крутим-вертим, намечая, как будем резать модель на куски.<br>
