Промелькнула мысль: а не много ли плоскостей для такой, не очень сложной, формы модели?<br>
Практика и бета ответят на этот вопрос.<br>
Экспорт в Пепу и распределение по листам. Муторно, но это нужно сделать, чтобы части развертки находились на одном листе и, как можно меньше, приходилось их искать на других листах при сборке. Кроме того, чем плотнее развертки будут на листе, тем меньше потребуется материала при печати.<br>
&nbsp;<br>
Итак, борьба с текстурой продолжается. Не получается "победить" размытие текстуры, пилы и зубцы линий. А значит, дедлайн отодвигается.<br>
<br>
Июль 2023.<br>Чтобы понять, какая модель получается, распечатал в том виде, какая есть и понял ... что перестарался!<br>
Я опасался, что из-за сложной выпуклой формы корабля она будет сложной и в сборке.  Разбил модель на модули (по примеру Мерлина). Это оказалось не правильным решением, т.к. при монтаже модулей они неизменно мялись.<br>
Изменю подход: <br>
1. Большую часть корабля сделаю одним модулем. Каркас слегка упрощу, а обшивку создам так, чтобы можно было последовательно ее монтировать на каркас, получая монолит<br>
2. Вторым модулем будет двигательный отсек+отдельные детализации. Что радует: решетка двигателя получилась отлично - даже при грубой бета сборке все встает как надо!))<br>
