Определились.<br>
Теперь проводим ревизию на предмет "сдвигов". <br>
<i>Те, кто уже работал с 3DReaper прекрасно знают, что в зависимости от угла съемки, модель значительно "ведет", искажаются ее формы, координаты точек, модель сжимается-растягивается, наблюдаются сдвиги и т.п. Приходится сначала выравнить модель по вертикали, вращая, найти положение, при котором максимальное число точек на противоположных краях будут наиболее близкими друг к другу, далее сводить диаметрально противоположные вертексы к средней общей вручную.</i><br>
