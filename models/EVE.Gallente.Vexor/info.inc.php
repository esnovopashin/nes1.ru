    <p>Дочь занимается на факультативе по программированию.<br>
	Однажды, по аватарке в Вайбере ее преподаватель узнал, что я летал в EVE. Разговорились. Поднялась тема бумажных моделей.<br>
Наступили карантикулы и занятия перешли в online формат.<br>От преподавателя поступил заказ моделек корааблей Gallente из EVE<br>
